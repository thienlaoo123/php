/**
 * Функция для подключения к базе данных MySQL
 * @return mysqli Объект соединения с базой данных
 */
function connectToDb(): mysqli
{
    // Создаем новое соединение с MySQL сервером
    $connection = new mysqli(DB_HOST, DB_USER, DB_PASSWORD, DB_NAME);

    // Проверяем успешность подключения
    if ($connection->connect_error) {
        // Если подключение не удалось, завершаем скрипт с сообщением об ошибке
        die("Ошибка подключения к базе данных: " . $connection->connect_error);
    }

    // Устанавливаем кодировку соединения для корректной работы с русскими символами
    $connection->set_charset(DB_CHARSET);

    return $connection;
}

/**
 * Функция для фильтрации и очистки входных данных от пользователя
 * @param mysqli $connection Соединение с базой данных (нужно для mysqli_real_escape_string)
 * @param string $data Входные данные для очистки
 * @return string Очищенные и безопасные данные
 */
function filterInput(mysqli $connection, string $data): string
{
    // Удаляем лишние пробелы в начале и конце строки
    $data = trim($data);
    
    // Преобразуем специальные символы в HTML-сущности для защиты от XSS-атак
    $data = htmlspecialchars($data, ENT_QUOTES | ENT_HTML5, 'UTF-8');
    
    // Экранируем специальные символы для безопасного использования в SQL-запросах
    $data = $connection->real_escape_string($data);
    
    return $data;
}

